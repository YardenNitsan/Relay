import {mkdir,open,rmdir,unlink} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import type {DockerSandbox} from './sandbox.js';
import type {ToolStore} from './store.js';
import {inspectPath} from './platform.js';
import type {Guard} from './files.js';
import {CODE_EVALUATION_HARNESS,codeEvaluationInputs,codeExecutionReceiptSchema,codeHash,codeHarnessDigest,codeSandboxIdentitySchema,gradeCodeExecution,type CodeSandboxIdentity,type CodeSample} from '../models/code-evaluation.js';

/** Internal verifier. The caller serializes with ordinary broker commands and
 * supplies fresh durable authorization. Generated bytes are never host code. */
export class CodeEvaluationSandbox {
  constructor(private readonly store:ToolStore,private readonly sandbox:Pick<DockerSandbox,'run'|'status'>){}
  status(){return this.sandbox.status('node');}
  private async staged<T>(files:Map<string,string>,guard:Guard,work:(path:string)=>Promise<T>):Promise<T>{
    guard();await this.store.init();const relative=`runs/code-evaluation-${randomUUID()}`,path=await inspectPath(this.store.root,relative);await mkdir(path,{mode:0o700});
    const written:string[]=[];
    try{for(const [name,content]of files){guard();const target=await inspectPath(path,name),handle=await open(target,'wx',0o600);written.push(name);try{await handle.writeFile(content);await handle.sync();}finally{await handle.close();}}guard();return await work(path);}
    finally{for(const name of written)await unlink(await inspectPath(path,name));await rmdir(await inspectPath(this.store.root,relative));}
  }
  async preflight(signal:AbortSignal,guard:Guard):Promise<CodeSandboxIdentity>{
    const available=await this.status();guard();if(!available.available)throw new Error(available.reason);
    return this.staged(new Map(),guard,async path=>{const result=await this.sandbox.run(path,['/usr/local/bin/node','-e','process.stdout.write("relay-code-evaluation-ready")'],15,signal,guard,'node');guard();
      if(result.exitCode!==0||result.truncated||result.stdout!=='relay-code-evaluation-ready'||result.files.size||result.toolchain?.profile!=='node')throw new Error('Executable evaluation sandbox preflight did not verify a clean Node environment');
      return codeSandboxIdentitySchema.parse({imageId:result.imageId,toolchainVersion:result.toolchain.version,harnessDigest:codeHarnessDigest});
    });
  }
  async verify(caseId:string,source:string,expected:CodeSandboxIdentity,signal:AbortSignal,guard:Guard):Promise<CodeSample>{
    codeSandboxIdentitySchema.parse(expected);if(Buffer.byteLength(source)>32768||!source||source.includes('\0'))throw new Error('Invalid bounded evaluation source');
    const files=new Map([['solution.cjs',source],['runner.cjs',CODE_EVALUATION_HARNESS],['inputs.json',JSON.stringify(codeEvaluationInputs(caseId))]]);
    return this.staged(files,guard,async path=>{
      const result=await this.sandbox.run(path,['/usr/local/bin/node','--max-old-space-size=128','/workspace/runner.cjs'],15,signal,guard,'node');guard();
      if(result.imageId!==expected.imageId||result.toolchain?.profile!=='node'||result.toolchain.version!==expected.toolchainVersion)throw new Error('Executable evaluation sandbox identity changed');
      if(result.files.size!==files.size||[...files].some(([name,content])=>result.files.get(name)!==content))throw new Error('Evaluation source, input or harness was modified during execution');
      const receipt=codeExecutionReceiptSchema.parse({imageId:result.imageId,toolchainVersion:result.toolchain.version,harnessDigest:codeHarnessDigest,sourceSha256:codeHash(source),outputSha256:codeHash(result.stdout),exitCode:result.exitCode,truncated:result.truncated,durationMs:result.durationMs});
      return {caseId,grade:gradeCodeExecution(caseId,result),receipt};
    });
  }
}
