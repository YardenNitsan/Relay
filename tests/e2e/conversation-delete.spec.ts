import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {chooseExecutionOption, pairBrowser } from './helpers';

test('phone history deletion requires confirmation and stays absent after reload and search', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' });
  await page.goto('/'); await pairBrowser(page);
  const title = 'Deletehistorysentinel completed conversation';
  await chooseExecutionOption(page,'Compute depth','fast');
  await page.getByRole('textbox', { name: 'Objective' }).fill(title);
  await page.getByRole('button', { name: 'Send objective', exact: true }).click();
  await expect(page.getByText('Completed', { exact: true }).first()).toBeVisible({ timeout: 20_000 });
  const conversationId = new URL(page.url()).searchParams.get('conversation');
  expect(conversationId).toBeTruthy();
  await page.getByRole('button', { name: 'Open conversation history', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Conversations', exact: true });
  const row = dialog.locator('.history-row').filter({ has: page.getByRole('button', { name: new RegExp(title) }) });
  await row.getByRole('button', { name: 'Delete conversation', exact: true }).click();
  const confirmation = dialog.getByRole('region', { name: 'Confirm conversation deletion' });
  await expect(confirmation.getByText(title, { exact: true })).toBeVisible();
  await expect(confirmation).toContainText('audit');
  await expect(confirmation).toContainText('Workspace files');
  await expect(confirmation.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
  await page.screenshot({ path: 'output/playwright/history-delete-phone.png' });
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(confirmation).toHaveCount(0);
  await expect(row.getByRole('button', { name: 'Delete conversation', exact: true })).toBeFocused();
  await expect(page).toHaveURL(new RegExp(`conversation=${conversationId}`));

  await row.getByRole('button', { name: 'Delete conversation', exact: true }).click();
  await confirmation.getByRole('button', { name: 'Delete conversation', exact: true }).click();
  await expect(page).not.toHaveURL(/conversation=/);
  await page.reload();
  await expect(page.getByRole('heading', { name: /What should we/ })).toBeVisible();
  await page.getByRole('button', { name: 'Open conversation history', exact: true }).click();
  await dialog.getByLabel('Search history', { exact: true }).fill('Deletehistorysentinel');
  await dialog.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(dialog.getByRole('heading', { name: 'No matching history', exact: true })).toBeVisible();
  await dialog.getByLabel('Search in', { exact: true }).selectOption('messages');
  await expect(dialog.getByRole('heading', { name: 'No matching history', exact: true })).toBeVisible();
  expect((await page.request.get(`/api/conversations/${conversationId}`)).status()).toBe(404);
});

test('deleting unfinished work shows the host refusal and keeps the conversation', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/'); await pairBrowser(page);
  await page.getByRole('button', { name: /Bring a project/ }).click();
  await page.getByRole('dialog',{name:'Workspaces',exact:true}).getByRole('button',{name:'New workspace',exact:true}).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Deletion approval workspace');
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await expect(page.getByRole('region',{name:'Project inspector',exact:true}).getByRole('heading',{name:'Deletion approval workspace',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await chooseExecutionOption(page,'Computer access','supervised');
  await page.getByRole('textbox', { name: 'Objective' }).fill('Create a file for unfinished history deletion');
  await page.getByRole('button', { name: 'Send objective', exact: true }).click();
  await page.getByRole('button', { name: 'Activity', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Allow once', exact: true })).toBeVisible();
  const conversationUrl = page.url();
  await page.getByRole('button', { name: 'Open conversation history', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Conversations', exact: true });
  const row = dialog.locator('.history-row').filter({ has: page.getByRole('button', { name: /Create a file for unfinished history deletion/ }) });
  await row.getByRole('button', { name: 'Delete conversation', exact: true }).click();
  const confirmation = dialog.getByRole('region', { name: 'Confirm conversation deletion' });
  const refusal = page.waitForResponse(response => response.request().method() === 'DELETE' && response.url().includes('/api/conversations/'));
  await confirmation.getByRole('button', { name: 'Delete conversation', exact: true }).click();
  expect((await refusal).status()).toBe(409);
  await expect(confirmation.getByRole('alert')).toContainText(/stop|cancel/i);
  await expect(page).toHaveURL(conversationUrl);
  await expect(confirmation.getByRole('button', { name: 'Delete conversation', exact: true })).toBeEnabled();
  await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(row).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Cancel task', exact: true }).click();
  await expect(page.getByText('Cancelled', { exact: true }).first()).toBeVisible();
});
